 // The piece is a sphere made of nearly three thousand particles, each one assigned to a different frequency in the sound spectrum. 
// When the microphone is off, the sphere drifts quietly, cycling through soft colors. When the mic turns on, every sound in the room shapes what the sphere becomes. Bass notes punch the particles outward in shockwaves. Higher frequencies make them sparkle and bloom. Loud moments stretch the whole sphere wider; quiet ones let it breathe and settle. Floating stars swim around the surface at their own rhythms. 
// I also wanted users to be able to customize and interact with it even more, so I added a color picker. Where you can pick any combination of colors and how many colors you want.
// However, music is something a lot of people assume everyone experiences the same way, but deaf and hard-of-hearing people often experience sound differently, through vibration, rhythm, or not at all. And as I am interested in assistive technology, I wanted this piece to be something they could use too. Instead of only hearing a song, they could watch it move through space. 
// Sound is everywhere, in conversations, in songs, even in quiet rooms, and it constantly affects how we feel without us realizing. By making sound visible, I wanted to make the impact of sound seen, I wanted to see what I was hearing, what other people were hearing.

// adjustable parameters
// constant values used as the main configuration settings for the visualization
// these values stay fixed unless manually changed
 
const NUM_PARTICLES = 2800; // total number of particles rendered in the sphere, higher values increase density/detail but also increase rendering cost
const BASE_RADIUS = 180; // default radius of the sphere when there is no audio influence, acts as the sphere's resting size
const FFT_BANDS = 256; // number of frequency bins generated by FFT analyzer, determines frequency resolution for audio analysis
const WARP_SCALE = 1.4; // multiplier controlling how far particles are pushed outward based on their assigned frequency energy
const AMP_SCALE = 100; // multiplier converting average audio loudness into overall sphere size expansion
const BEAT_THRESHOLD = 0.22; // minimum bass jump required to classify a sudden bass increase as a beat
const BEAT_DECAY = 0.05; // amount beat pulse intensity decreases each frame after a beat
const ORBIT_SPEED = 0.0006; // angular increment added every frame to rotate sphere around y-axis
const TRAIL_ALPHA = 18; // opacity of translucent black background overlay used to create motion trails, lowered slightly so swimming trails linger longer
const FLY_FORCE = 18; // the amount of outward velocity added to every particle along its own direction away from the sphere center when a beat is detected and higher values cause particles to explode further out from the surface and take longer to spring back, while lower values produce a smaller subtle pulse
const RETURN_EASE = 0.03; // spring force strength pulling particles back toward their target positions, lowered so particles drift back slowly and feel fluid rather than snapping
const DAMPING = 0.88; // velocity decay factor simulating friction/air resistance, raised so particles coast further and carry more momentum when swimming
const SWIM_SPEED = 0.0014; // rate at which each particle's swim offset angle advances per frame, controls how fast particles undulate around the sphere surface
const SWIM_RADIUS = 14; // maximum radial ripple distance in pixels — kept small so the sphere silhouette stays clean while still visibly breathing with the sound
 
 
