// fisher-yates shuffle
// randomizes array order using unbiased in-place swapping
 
function shuffleArray(arr) { // creates a function called shuffleArray that takes in an array and will randomize the order of its elements
  for (let i = arr.length - 1; i > 0; i--) { // starts at the last index of the array and loops backward until reaching index 1
    let j = floor(random(i + 1)); // generates a random whole number between 0 and the current index i
    let tmp = arr[i]; // stores the current array value temporarily so it is not lost during swapping
    arr[i] = arr[j]; // replaces the current value with the randomly selected value
    arr[j] = tmp; // places the original stored value into the random position to complete the swap
  }
 
  return arr; // returns the newly shuffled version of the array after all swaps are finished
}
 
// fibonacci sphere generation 
// creates evenly distributed points across sphere surface
function buildFibSphere(count) { // creates a function that generates a sphere made of evenly spaced particles based on the total number requested
  let pts = []; // creates an empty array that will store every generated particle object
  const golden = PI * (3 - sqrt(5)); // calculates the golden angle used to evenly distribute points around the sphere
  
  let bands = []; // creates an empty array that will store FFT frequency band assignments for each particle
  
  for (let i = 0; i < count; i++) { // loops once for every particle that needs to be created
    bands.push(floor(map(i, 0, count - 1, 0, FFT_BANDS - 1))); // maps each particle index into a valid FFT band number and adds it to the bands array
  }
 
  shuffleArray(bands); // randomizes the order of FFT bands so nearby particles are not assigned similar frequencies
 
  for (let i = 0; i < count; i++) { // loops through again to actually create each particle object
    
    let yn = 1 - (i / (count - 1)) * 2; // calculates the particle's vertical position from top (+1) to bottom (-1) of the sphere
    let r = sqrt(max(0, 1 - yn * yn)); // calculates the horizontal radius at this vertical slice of the sphere
    let phi = golden * i; // calculates the angle around the sphere using the golden angle pattern
    let nx = cos(phi) * r; // calculates the normalized x direction of the particle on the sphere
    let ny = yn; // stores the normalized y direction of the particle
    let nz = sin(phi) * r; // calculates the normalized z direction of the particle
 
    pts.push({ // adds a new particle object into the pts array
    nx, ny, nz, // stores the normalized direction vector showing which way the particle points outward
      band: bands[i], // assigns this particle one of the shuffled FFT frequency bands
 
      cx: nx * BASE_RADIUS, // sets the particle's starting x position on the sphere surface
      cy: ny * BASE_RADIUS, // sets the particle's starting y position on the sphere surface
      cz: nz * BASE_RADIUS, // sets the particle's starting z position on the sphere surface
 
      vx: 0, vy: 0, vz: 0, // sets starting velocities to 0 so the particle begins completely still
      swimAngle: random(TWO_PI), // each particle gets a unique random starting angle so they all swim out of phase with each other and never pulse in unison — this angle advances every frame to create the continuous swimming motion
    });
  }
 
  return pts; // returns the completed array containing all generated particles
}
 
// getCustomHue
// returns the appropriate hue for a particle given its band index and the current frame
// if the user has selected one or more custom colors, it cycles through ONLY those chosen hues,if no colors are selected, it goes back to the original full-rainbow behavior so the sphere looks unchanged by default
// bandIndex is the particle's FFT band used to spread colors across the sphere
// timeShift is the speed multiplier that controls how fast colors cycle over time

function getCustomHue(bandIndex, timeShift) { // takes the particle's frequency band and a time-cycling speed multiplier, returns a final hue value 0-360
  if (selectedHues.length === 0) { // no custom colors have been picked, fall back to the original rainbow palette so the default visual is preserved exactly
    return (map(bandIndex, 0, FFT_BANDS - 1, 0, 360) + frameCount * timeShift) % 360; // original full-spectrum hue calculation mapping band index across the entire color wheel and shifting over time
  }
  // user has picked one or more custom colors, build the palette from only those hues
  let index = floor(map(bandIndex, 0, FFT_BANDS - 1, 0, selectedHues.length)) % selectedHues.length; // maps the particle's band across the chosen palette so different bands get different chosen colors, modulo prevents out-of-bounds access at the last band
  let baseHue = selectedHues[index]; // picks the chosen hue assigned to this particle's band slot from the user's selected palette
  let wobble = sin(frameCount * timeShift * 0.05 + bandIndex) * 8; // small ±8 degree hue wobble over time so colors feel alive and breathing rather than perfectly static, sine wave offset by band index so neighboring particles don't wobble in lockstep
  return (baseHue + wobble + 360) % 360; // applies the wobble and wraps to stay in valid 0-360 hue range, +360 before modulo prevents negative values from sine when wobble is at its minimum
}

// makeSwatchHandler
// factory function that builds and returns a click handler for a given swatch button
// declared outside the swatch creation loop so the linter doesn't warn about defining functions inside loops
// takes the swatch element as input and returns a closure that toggles its selection state when called

function makeSwatchHandler(swatch) { // takes a single swatch button element and returns the function that should run when that swatch is clicked
  return function() { // returns a closure tied to this specific swatch so each swatch gets its own handler that knows which button it belongs to
    let isSelected = swatch.attribute("data-selected") === "true"; // reads the current selection state from the data attribute and converts to a boolean for the toggle logic
    let hue = parseFloat(swatch.attribute("data-hue")); // reads the hue value back from the data attribute and converts it to a number so it can be used in palette calculations
    if (isSelected) { // swatch is currently selected so this click should deselect it removing the color from the palette
      selectedHues = selectedHues.filter(h => h !== hue); // creates a new array containing every hue except this one effectively removing it from the active palette
      swatch.attribute("data-selected", "false");
      swatch.attribute("aria-pressed", "false"); // updates the data attribute to reflect the new deselected state for the next click
      swatch.style("border-color", "#333333"); // reverts the border back to dark grey indicating the swatch is no longer selected
      swatch.style("transform", "scale(1.0)"); // shrinks the swatch back to its default size confirming deselection visually
    } else { // swatch is currently deselected so this click should select it adding the color to the palette
      selectedHues.push(hue); // adds the new hue to the active palette so the sphere will start cycling through it
      swatch.attribute("data-selected", "true");
      swatch.attribute("aria-pressed", "true"); // updates the data attribute to reflect the new selected state for the next click
      swatch.style("border-color", "#ffffff"); // bright white border clearly marks the swatch as currently selected so the user can see at a glance which colors are active
      swatch.style("transform", "scale(1.15)"); // slightly enlarges the swatch confirming selection with a satisfying visual response
    }
  };
}

