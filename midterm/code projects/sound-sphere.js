// Portfolio integration: handle permission failures and stop the mic completely.
let micRequest = 0;
function stopMicrophone() {
  micRequest++;
  if (micSource) { micSource.disconnect(); micSource = null; }
  if (micStream) { micStream.getTracks().forEach(track => track.stop()); micStream = null; }
  if (audioCtx) { audioCtx.close().catch(() => {}); audioCtx = null; }
  micActive = false;
  audioReady = false;
  prevBassAvg = 0;
  if (micBtn) {
    micBtn.removeAttribute('disabled');
    micBtn.html('MIC OFF');
    micBtn.attribute('aria-pressed', 'false');
    micBtn.style('color', '#aaaaaa');
    micBtn.style('border-color', '#555555');
  }
}
async function toggleMic() {
  const status = document.getElementById('sketch-status');
  if (micActive) { stopMicrophone(); status.textContent = 'Microphone off'; return; }
  if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) {
    status.textContent = 'Microphone needs HTTPS or localhost. The animation still works without it.';
    return;
  }
  const request = ++micRequest;
  micBtn.attribute('disabled', '');
  status.textContent = 'Waiting for microphone permission…';
  try {
    audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    await audioCtx.resume();
    const stream = await navigator.mediaDevices.getUserMedia({audio: true});
    if (request !== micRequest) { stream.getTracks().forEach(track => track.stop()); return; }
    micStream = stream;
    analyser = audioCtx.createAnalyser();
    analyser.fftSize = FFT_BANDS * 2;
    analyser.smoothingTimeConstant = 0.85;
    dataArray = new Uint8Array(analyser.frequencyBinCount);
    micSource = audioCtx.createMediaStreamSource(stream);
    micSource.connect(analyser);
    audioReady = micActive = true;
    loop();
    micBtn.html('MIC ON');
    micBtn.attribute('aria-pressed', 'true');
    micBtn.style('color', '#88ffaa');
    status.textContent = 'Microphone on · sound stays in your browser';
  } catch (error) {
    if (request !== micRequest) return;
    stopMicrophone();
    status.textContent = 'Microphone unavailable or permission denied. You can still explore the colors.';
  } finally {
    if (request === micRequest) micBtn.removeAttribute('disabled');
  }
}

function draw() { // main animation loop that updates and redraws everything every frame
 
  push(); // saves the current drawing settings and transformations
  translate(-width / 2, -height / 2, 0); // shifts the coordinate system so a rectangle can cover the whole screen
  noStroke(); // removes outlines from the fade rectangle
  fill(0, 0, 0, TRAIL_ALPHA); // sets a transparent black color used to create motion trails
  rect(0, 0, width, height); // draws a fullscreen transparent rectangle to slowly fade previous frames
  pop(); // restores the previous drawing settings and transformations
 
  drawingContext.clear(drawingContext.DEPTH_BUFFER_BIT);
  scale(min(1, width / 620, height / 620)); // Fit the sphere on smaller screens.
  autoRotY += ORBIT_SPEED; // adds a small amount to y rotation every frame so the sphere slowly spins
 
 
// idle state when there is no audio
if (!micActive) { // checks if microphone has not been initialized yet OR has been turned off via the button
 
    push(); // saves current transformations
    rotateX(0.4); // tilts the sphere slightly forward
    rotateY(autoRotY); // rotates the sphere around the y-axis over time
 
for (let i = 0; i < particles.length; i++) { // loops through every particle to draw it
  
  let p = particles[i]; // gets the current particle from the particles array
  let hue = getCustomHue(p.band, 0.3); // uses the custom hue helper which respects the user's selected color palette or falls back to the original rainbow if no colors are selected, 0.3 is the original idle-state cycling speed
  let sparkle = random(1) < 0.018; // randomly decides whether this particle should sparkle this frame, kept low so only a small number of particles sparkle at any moment giving a subtle glitter effect rather than the whole sphere flashing
 
if (sparkle) { // runs if sparkle is true

        noStroke(); // disables stroke so only the filled star shape is visible with no outline around it
        fill(hue, 60, 100, 100); // colored sparkle core — uses the cycling hue at saturation 60 and full brightness so sparkles appear as vivid colored stars rather than plain white, making the idle sphere look like a galaxy of colorful glittering stars
        drawStar4(p.nx * BASE_RADIUS, p.ny * BASE_RADIUS, p.nz * BASE_RADIUS, random(3.5, 7.0)); // draws a sharp 4-pointed star, size range raised from 2.5-5 to 3.5-7 so sparkles are visibly bigger and more prominent against the dark background
        fill(hue, 30, 100, 40); // same hue but lower saturation and 40 opacity — creates a wide soft colored glow bloom around the bright core star
        drawStar4(p.nx * BASE_RADIUS, p.ny * BASE_RADIUS, p.nz * BASE_RADIUS, random(9, 16)); // glow star size range raised from 6-10 to 9-16 so the bloom spreads wider and the sparkle feels more dramatic
 
} else { // runs if sparkle is false

        noStroke(); // disables stroke so only the filled star shape renders with no border
        fill(hue, 70, 85, 85); // saturation raised from 30 to 70 and brightness from 65 to 85 and opacity from 70 to 85 so regular idle particles are much more vivid and colorful rather than dim grey specks, giving the whole idle sphere a rich glowing appearance
        drawStar4(p.nx * BASE_RADIUS, p.ny * BASE_RADIUS, p.nz * BASE_RADIUS, 1.2); // draws a small 4-pointed star at a fixed size of 1.2px for regular idle particles, kept small so the sphere looks like a field of tiny stars at rest
  }
}
 
pop(); // restores transformations after drawing idle sphere
return; // stops the function here so audio code does not run before mic starts
  }
 
// audio analysis
 
analyser.getByteFrequencyData(dataArray); // fills dataArray with the newest FFT frequency values from the microphone
  
let total = 0; // creates a variable starting at 0 to store the sum of all frequency values
for (let i = 0; i < dataArray.length; i++) total += dataArray[i]; // loops through the entire dataArray and adds up all frequency values into total
  
  let ampLevel = (total / dataArray.length) / 255; // calculates the average frequency value and converts it into a number between 0 and 1
  
let bassSum = 0; // creates a variable to store the combined low-frequency values
for (let i = 0; i < 12; i++) bassSum += dataArray[i]; // loops through the first 12 frequency bins and adds them together to measure bass energy
  
  let bassAvg = bassSum / (12 * 255); // divides bass sum into a normalized number between 0 and 1
  
  let isBeat = bassAvg - prevBassAvg > BEAT_THRESHOLD; // checks whether bass increased enough from the previous frame to count as a beat
 
beatPulse = isBeat ? 1.0 : max(0, beatPulse - BEAT_DECAY); // sets beatPulse to 1 on a beat, otherwise slowly decreases it toward 0
prevBassAvg = lerp(prevBassAvg, bassAvg, 0.2); // smoothly updates previous bass value toward the current bass value
 
  let dynRadius = BASE_RADIUS + ampLevel * AMP_SCALE; // increases sphere radius based on current sound loudness
 
for (let i = 0; i < particles.length; i++) { // loops through every particle in the system so each one can be individually updated every frame
 
  let p = particles[i]; // gets the current particle object so we can modify its position and velocity
  let freq = dataArray[p.band] / 255; // takes the particle's assigned FFT frequency value and normalizes it into a 0–1 range

  let tr = dynRadius + freq * dynRadius * WARP_SCALE; // calculates the target radius for this particle based on audio energy and warp strength

  let tx = p.nx * tr; // calculates the target x position by scaling the particle's direction vector by the target radius
  let ty = p.ny * tr; // calculates the target y position in the same way to keep it on the sphere surface
  let tz = p.nz * tr; // calculates the target z position so the particle stays on the spherical shape
 
  if (isBeat) { // checks if a beat was detected in the current frame
 
    let kick = FLY_FORCE * (1.0 + ampLevel * 2.0); // calculates how strong the outward explosion force should be based on loudness
 
    p.vx += p.nx * kick; // pushes the particle outward along its x direction during a beat
    p.vy += p.ny * kick; // pushes the particle outward along its y direction during a beat
    p.vz += p.nz * kick; // pushes the particle outward along its z direction during a beat
  }
 
  p.vx += (tx - p.cx) * RETURN_EASE; // applies a spring-like force pulling the particle toward its target x position
  p.vy += (ty - p.cy) * RETURN_EASE; // applies the same spring force in the y direction
  p.vz += (tz - p.cz) * RETURN_EASE; // applies the same spring force in the z direction
 
  p.vx *= DAMPING; // reduces x velocity slightly to simulate friction and prevent infinite acceleration
  p.vy *= DAMPING; // reduces y velocity for the same stabilizing effect
  p.vz *= DAMPING; // reduces z velocity so motion gradually settles instead of oscillating forever
 
  p.cx += p.vx; // updates the particle's x position by adding its current velocity
  p.cy += p.vy; // updates the particle's y position using velocity-based motion
  p.cz += p.vz; // updates the particle's z position so it actually moves in 3D space
}
 
 
// rendering setup for sphere
// prepares transformation state and draws the full particle system in 3D
 
push(); // saves the current coordinate system so transformations don't affect other drawings
rotateX(0.4); // tilts the entire sphere slightly forward so it's viewed at an angle
rotateY(autoRotY); // continuously rotates the sphere around the y-axis over time
drawSphere(); // calls the function that actually renders all particles to the screen
drawFloatingStars(ampLevel); // draws the separate floating 4-pointed stars that swim around the sphere surface on top of the main particle system
pop(); // restores the previous coordinate system after drawing is complete
}
 
// rendering
// draws each particle as a visible point
 
function drawSphere() { // function that renders every particle each frame based on updated physics + audio data
 
  for (let i = 0; i < particles.length; i++) { // loops through every particle so each one gets drawn individually
 
    let p = particles[i]; // retrieves the current particle being drawn
    let freq = dataArray[p.band] / 255; // gets the audio energy for this particle's assigned frequency band and normalizes it
    let hue = getCustomHue(p.band, 0.4); // uses the custom hue helper which respects the user's selected color palette or falls back to the original rainbow if no colors are selected, 0.4 is the original active-mode cycling speed
   let sparkle = random(1) < 0.012; // randomly decides if this particle should appear as a bright sparkle this frame
 
    if (sparkle) { // runs sparkle rendering mode for visually emphasized particles

      strokeWeight(random(2.5, 5.0)); // sets a thicker stroke to create a bright particle core
      stroke(hue, 90, 100, 100); // full saturation and full brightness sparkle so it pops vividly against the dark background
      point(p.cx, p.cy, p.cz); // draws the main sparkle point at the particle's 3D position

      strokeWeight(random(6, 10)); // increases size to create a glow-like outer layer
      stroke(hue, 60, 100, 35); // glow uses same hue but lower saturation and semi-transparent so it blooms softly around the core
      point(p.cx, p.cy, p.cz); // draws the glow over the same position for a layered effect

} else { // normal rendering mode for standard particles

      let sat = map(freq, 0, 1, 20, 85); // maps audio energy to color saturation so louder sound makes colors richer
      let bri = map(freq, 0, 1, 72, 100); // maps audio energy to brightness so louder sound makes particles brighter
      let alp = map(freq, 0, 1, 65, 100); // maps audio energy to opacity so louder sound makes particles more visible

      strokeWeight(map(freq, 0, 1, 1.2, 3.2)); // increases particle thickness when audio energy is higher
      stroke(hue, sat, bri, alp); // sets final particle color using computed hue, saturation, brightness, and alpha
      point(p.cx, p.cy, p.cz); // renders the particle at its current 3D position on the sphere
    }
  }
}

// drawFloatingStars
// updates and draws the floating 4-pointed stars that swim around the sphere surface
// completely separate from the main particle system so the original audio-reactive point behaviour is untouched
// ampLevel is passed in so stars grow bigger and brighter when loud sound is detected

function drawFloatingStars(ampLevel) {
  for (let i = 0; i < floatingStars.length; i++) { // loops through every floating star so each one is updated and drawn every frame
    let s = floatingStars[i]; // gets the current floating star object

    s.swimAngle += s.swimSpeed; // advances this star's swim angle by its personal speed each frame — because each star has a unique swimSpeed they all move at different rates, some darting and some drifting

    let swimAmt = BASE_RADIUS * 0.18 + ampLevel * BASE_RADIUS * 0.25; // calculates how far the star swims laterally around the sphere surface: a base wander amount plus an extra push from overall loudness so stars swim wider arcs when sound is loud
    let swimX = sin(s.swimAngle) * swimAmt; // x component of the swim offset using sine which moves the star horizontally around the sphere
    let swimY = cos(s.swimAngle * 0.8) * swimAmt; // y component using cosine at a slightly different rate (0.8) so x and y fall out of sync, making the path an ellipse rather than a perfect circle
    let swimZ = sin(s.swimAngle * 0.6) * swimAmt * 0.7; // z component at yet another rate (0.6) so all three axes are out of phase, creating a smooth flowing 3D looping path that looks organic

    let r = BASE_RADIUS + ampLevel * 30; // the star orbits at just above BASE_RADIUS, expanding outward by up to 30px when loud so floating stars pulse with the overall sound energy
    let x = s.nx * r + swimX; // final x position = outward direction scaled to the orbit radius plus the lateral swim offset
    let y = s.ny * r + swimY; // final y position combining radial and swim components
    let z = s.nz * r + swimZ; // final z position completing the 3D position of this floating star

    let starSize = 4 + ampLevel * 10; // base size of 4px growing up to 14px at full loudness so floating stars visibly pulse and bloom with the sound
    let brightness = 80 + ampLevel * 20; // base brightness of 80 rising to 100 at full loudness so stars get brighter and more vivid when sound is detected
    let alpha = 70 + ampLevel * 30; // base opacity of 70 rising to 100 so stars are always visible but become more prominent during loud moments

    noStroke(); // no outline on the floating star, only the filled shape is drawn
    fill(s.hue, 80, brightness, alpha); // fills the star with its personal hue at high saturation so each floating star has a rich distinct color that pulses in brightness and opacity with the sound
    drawStar4(x, y, z, starSize); // draws the 4-pointed star at its current swimming position using the audio-driven size

    fill(s.hue, 40, 100, alpha * 0.3); // same hue but low saturation and 30% of the main opacity, creates a soft glow halo bloom around the core star
    drawStar4(x, y, z, starSize * 2.2); // draws a larger star behind the core to create the glow, 2.2x the core size so the bloom spreads visibly outward
  }
}

// draws 4-pointed stars centered by the 3D sphere with the given size
// called instead of point() for every particle so all particles render as sharp 4-pointed stars rather than round dots

function drawStar4(x, y, z, size) { // takes the 3D center position x,y,z and a size value controlling how far the tips of the star extend from the center
  let outer = size;         // outer is the distance from the center to each of the 4 sharp tips, this is the full reach of the star points
  let inner = size * 0.15;  // inner is the distance from the center to the pinch points between tips, 0.15 makes the waist very tight and narrow, matching the pointed 4-star reference shape
  beginShape();             // tells p5 to start recording a custom polygon made of vertices rather than using a preset shape like ellipse or rect
  for (let i = 0; i < 8; i++) { // loops 8 times to place 4 outer tips and 4 inner pinch points alternating around the full circle and 8 total vertices make one complete 4-pointed star
    let angle = (i * TWO_PI) / 8 - HALF_PI; // divides the full circle (TWO_PI radians) into 8 equal slices and assigns this vertex its angle, subtracting HALF_PI rotates the whole star so the first tip points straight up rather than sideways
    let rad = (i % 2 === 0) ? outer : inner; // even-numbered vertices (0,2,4,6) get the outer tip radius, odd-numbered vertices (1,3,5,7) get the inner pinch radius, this alternating pattern is what creates the star silhouette
    vertex(x + cos(angle) * rad, y + sin(angle) * rad, z); // places this vertex at the correct 3D position by converting the polar angle and radius into x and y offsets added to the star center, z stays fixed so the star faces the camera
  }
  endShape(CLOSE); // closes the polygon by connecting the last vertex back to the first vertex, completing the star outline and filling it with the current fill color set before calling this function
}
 
 
